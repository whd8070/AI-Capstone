# 스펙 v1 + AC — 포트폴리오 설명·검증 챗봇

> 버전: v1 (2026-09-30) · 상위 문서: `problem-definition.md`, `ontology-v1.md`
> 관련 문서: `AGENTS.md` (에이전트 구현 계약)
> AC 임계값(%·개수)은 스파이크 결과에 따라 조정 가능하되, 조정 시 본 문서에 이력을 남긴다.

## 1. 개요

기존 포트폴리오 최적화 알고리즘이 산출한 투자비중을 입력으로 받아, **실시간 크롤링한 뉴스·시황 정보를 근거로 각 비중의 매수 이유를 설명하고, 그 설명의 모든 주장을 검증 에이전트가 출처와 대조해 통과된 내용만 사용자에게 전달**하는 챗봇. (문제정의서 §8 대응)

핵심 설계 원칙 — **설명의 성격 분리**: 최적화기의 비중은 수치 입력(수익률·공분산 등)에서 산출된 것이므로, 뉴스 기반 설명은 "비중의 산출 원인"이 아니라 "비중을 지지하거나 반박하는 현재 시장 정황"이다. 시스템은 이 둘을 혼동시키는 사후 합리화를 금지하며, UI 문구로 명시한다 (FR-06).

## 2. 스코프

**In:**
- 산출된 비중에 대한 설명 생성·검증·대화형 질의응답
- 뉴스·시황·공시의 실시간 수집과 시점 메타데이터 관리
- 설명 내 주장 단위 검증 파이프라인

**Out (하지 않는 것):**
- 포트폴리오 최적화 알고리즘 자체의 개발·개선 (기존 알고리즘을 외부 모듈로 사용)
- 투자 자문·권유 (정보 제공 목적 명시, NFR-03)
- 수익모델·과금 [ASM-05]
- 금융정책·공공지원 탐색 (문제정의서 §6에서 기각)

## 3. 사용자 시나리오

**S1 — 비중 근거 질의**: 사용자가 "왜 삼성전자 비중이 25%야?"라고 묻는다 → 시스템은 최적화기의 산출 맥락(팩터·기대수익 추정 근거)과, 수집된 최신 시장 정보 중 해당 자산 관련 항목을 출처·발행시각과 함께 연결해 답한다. 검증을 통과하지 못한 주장은 응답에 포함되지 않는다.

**S2 — 시황 변화 확인**: 사용자가 "오늘 반도체 뉴스 나온 거 내 포트폴리오에 영향 있어?"라고 묻는다 → Research Agent가 수집한 당일 정보 중 관련 항목을 요약하되, 비중 산출 시점 이후 정보는 "산출에 반영되지 않은 최신 참고 정보" 라벨로 구분해 답한다.

**S3 — 검증 실패 경로**: 설명 생성 결과에 출처 없는 주장이 포함됨 → Verification Agent가 반려 → 재생성(최대 N회) → 여전히 실패 시 "해당 부분은 확인된 출처가 없어 답할 수 없다"고 정직하게 응답한다.

## 4. 기능 요구사항 (FR) + AC

### FR-01. 포트폴리오 입력 수신 [PRJ]
최적화기 출력(자산별 비중, 산출 기준시점 `t_opt`, 사용된 입력 데이터 기간)을 표준 스키마로 수신한다.
- **AC-01a**: 입력 스키마에 `t_opt`가 없으면 시스템은 처리를 거부하고 오류를 반환한다. (시점 정합성의 전제조건)

### FR-02. 실시간 시장 정보 수집 — Research Agent [PAIN-04 → SUR-05]
- **AC-02a**: 수집된 모든 정보 항목은 (출처 URL, 발행시각 `t_pub`, 수집시각 `t_crawl`, 출처 등급) 4개 메타데이터를 갖는다. 누락 항목은 저장소에 적재되지 않는다.
- **AC-02b**: 출처 등급 체계(예: 공시·공식 > 언론 > 커뮤니티)가 문서로 정의되어 있고, 모든 적재 항목에 등급이 부여된다.
- **AC-02c (시점 정합성)**: `t_pub > t_opt`인 정보는 "비중 산출 근거" 풀에서 제외되고 "최신 참고 정보" 풀로만 분류된다. 분류 오류율은 테스트셋(경계 시각 포함 50건) 기준 0%.
- **AC-02d (최신성)**: 사용자 질의 시점 기준, 관심 자산의 최근 24시간 내 주요 정보가 수집 풀에 존재한다. (스파이크로 "주요"의 조작적 정의 확정 후 수치화)

### FR-03. 설명 생성 — Explanation Agent [PAIN-01 → SUR-01, SUR-07]
- **AC-03a**: 응답 내 모든 사실 주장(claim)에는 수집 풀 내 출처 ID가 1개 이상 연결된다. 출처 ID가 없는 주장의 생성은 프롬프트·스키마 수준에서 금지된다.
- **AC-03b**: 응답에 인용된 모든 수치(수익률·비중·지표)는 원출처 문서의 수치와 일치한다. 표본 20개 응답 수동 대조 시 일치율 100%.
- **AC-03c**: 응답은 출처의 발행시각을 함께 표기한다.

### FR-04. 검증 — Verification Agent [PAIN-05 → SUR-05, SUR-06]
검증은 3계층으로 조작적으로 정의된다: ① 출처 존재성(주장→출처 연결 여부), ② 주장-출처 정합성(entailment·수치 대조), ③ 시점 정합성(AC-02c 준수 여부).
- **AC-04a (출처 존재성)**: 의도적으로 무출처 주장 30개를 주입한 테스트셋에서 검출률 90% 이상.
- **AC-04b (정합성)**: 수치 왜곡·과장을 주입한 변조 테스트셋 30건에서 검출률 80% 이상. (임계값은 스파이크 후 조정)
- **AC-04c (차단 권한)**: 검증 실패 주장은 사용자에게 노출되지 않거나, 경고 라벨과 함께만 노출된다. 무라벨 노출 0건.
- **AC-04d (재생성 한도)**: 반려 시 설명 재생성은 최대 N회(기본 2회)이며, 초과 시 S3의 정직 실패 응답으로 전환된다.
- **AC-04e (감사 로그)**: 모든 판정(통과/반려/경고)은 주장 단위로 로그에 남고, 사후 재현 가능하다.

### FR-05. 대화 인터페이스 [PRJ]
- **AC-05a**: S1~S3 시나리오가 실제 대화로 수행 가능하다 (시연 기준).

### FR-06. 설명 성격의 구분 표시 [사후 합리화 방지, §1 원칙]
- **AC-06a**: 모든 응답에서 "산출 근거 관련 정보"와 "산출 이후의 최신 참고 정보"가 시각적·문구적으로 구분된다. 혼동 표기 0건 (표본 20개 검수).

## 5. 비기능 요구사항 (NFR) + AC

- **NFR-01 (확신 비용 압축)** [PAIN-02 → SUR-02]: 사용자가 수 시간~며칠 걸리던 교차확인을 대화로 대체한다.
  - AC: 단일 질의 응답 완료까지 파이프라인 전체(수집 캐시 활용 시) 60초 이내. (스파이크 후 조정)
- **NFR-02 (재현성)**: 동일 포트폴리오·동일 정보 풀 스냅샷 입력 시 검증 판정이 재현된다.
  - AC: 스냅샷 고정 테스트 10회 반복에서 판정 불일치 0건. (생성 텍스트는 달라도 판정은 동일해야 함)
- **NFR-03 (면책)**: 모든 세션 시작과 응답 하단에 "투자 자문이 아닌 정보 제공" 고지가 노출된다.
  - AC: 고지 누락 0건.

## 6. 리스크 및 제약

| 리스크 | 대응 |
|---|---|
| 사후 합리화 — 뉴스로 비중을 "설명"하는 것이 스토리텔링이 될 위험 | FR-06으로 성격 분리 표기, 발표·문서에서 supporting evidence임을 명시 |
| 크롤링 대상 사이트의 약관·robots.txt | 수집 대상 목록과 준수 정책을 Research Agent 스펙에 명문화 |
| LLM 환각이 검증 계층 자체에서 발생 | 검증의 ①·③계층은 규칙 기반(스키마·시각 비교)으로 구현해 LLM 의존 최소화, ②계층만 LLM+수치 파서 병행 |
| ASM 기각 가능성 | ASM-01 기각 시 대상 사용자 재정의(문제정의서 §7), 스펙 영향 범위: 시나리오 S1의 톤 |

